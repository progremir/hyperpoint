#!/bin/zsh
# Builds, signs and checks Hyperpoint.app at the path given ($1), stamped with an optional version ($2). It is signed
# with the hardened runtime notarization needs, and SIGN_TIMESTAMP=1 adds the secure timestamp it also needs.
# TCC keys the Accessibility and Input Monitoring grants to the app's designated requirement. An ad-hoc signature
# makes that a cdhash, which changes on every build and silently revokes both grants, so this refuses one unless
# ALLOW_ADHOC=1, for a build that only checks the pipeline.
#
# A build with a version is a release. One without is a development build: a separate app, Hyperpoint Dev, with its
# own bundle identifier, so installing it never replaces the release, and macOS keeps its grants apart from the
# release's.
set -euo pipefail
cd "${0:A:h}/.."

OUT="${1:?usage: build-app.sh <path/Hyperpoint.app> [version]}"
VERSION="${2:-}"
IDENTITY="${SIGN_IDENTITY:-Apple Development: Emir Amanbekov (KGBFPV5MVR)}"
BUNDLE_ID="dev.emir.hyperpoint"
[[ -n "$VERSION" ]] || BUNDLE_ID="dev.emir.hyperpoint.dev"

scripts/check-layers.sh
swift build -c release --product Hyperpoint
BIN="$(swift build -c release --show-bin-path)/Hyperpoint"
SPARKLE="$OUT/Contents/Frameworks/Sparkle.framework"

rm -rf "$OUT"
mkdir -p "$OUT/Contents/MacOS" "$OUT/Contents/Resources" "$OUT/Contents/Frameworks"
cp "$BIN" "$OUT/Contents/MacOS/Hyperpoint"
install_name_tool -add_rpath @executable_path/../Frameworks "$OUT/Contents/MacOS/Hyperpoint"
# Sparkle is thinned to the app's own architectures. Its XPC services are only for sandboxed apps, which Hyperpoint
# is not, so they are left out. ditto keeps the framework's symlinks, which its signature covers.
THIN=()
for arch in $(lipo -archs "$BIN"); do THIN+=(--arch "$arch"); done
ditto "${THIN[@]}" "${BIN:h}/Sparkle.framework" "$SPARKLE"
rm -rf "$SPARKLE/XPCServices" "$SPARKLE/Versions/B/XPCServices"
cp Support/Info.plist "$OUT/Contents/Info.plist"
if [[ -n "$VERSION" ]]; then
  plutil -replace CFBundleShortVersionString -string "$VERSION" "$OUT/Contents/Info.plist"
  plutil -replace CFBundleVersion -string "$(git rev-list --count HEAD)" "$OUT/Contents/Info.plist"
else
  plutil -replace CFBundleIdentifier -string "$BUNDLE_ID" "$OUT/Contents/Info.plist"
  plutil -replace CFBundleName -string "Hyperpoint Dev" "$OUT/Contents/Info.plist"
  plutil -replace CFBundleDisplayName -string "Hyperpoint Dev" "$OUT/Contents/Info.plist"
fi
# Only a Developer ID release reads the update feed. Sparkle would replace a development build with a release, which is
# the other app, and updating a release signed with any other identity would change its signature, so macOS would stop
# honoring the Accessibility and Input Monitoring grants. Without a feed, Sparkle never starts and the menu has no
# Check for Updates….
[[ -n "$VERSION" && "$IDENTITY" == "Developer ID Application:"* ]] || plutil -remove SUFeedURL "$OUT/Contents/Info.plist"
# Icons are generated by design/logo/build.py; the bundle takes them straight from the kit. Hyperpoint Dev gets the
# kit's dev icons under the same names.
ICONS=""
[[ -n "$VERSION" ]] || ICONS="-Dev"
cp "design/logo/macos/AppIcon$ICONS.icns" "$OUT/Contents/Resources/AppIcon.icns"
cp "design/logo/macos/MenuBarTemplate$ICONS.png" "$OUT/Contents/Resources/MenuBarTemplate.png"
cp "design/logo/macos/MenuBarTemplate$ICONS@2x.png" "$OUT/Contents/Resources/MenuBarTemplate@2x.png"
plutil -lint "$OUT/Contents/Info.plist" >/dev/null

TIMESTAMP=(--timestamp=none)
[[ "${SIGN_TIMESTAMP:-0}" == 1 ]] && TIMESTAMP=(--timestamp)
# Inside out, as Sparkle documents, and never --deep: the helpers first, then the framework, then the app.
for code in "$SPARKLE/Versions/B/Autoupdate" "$SPARKLE/Versions/B/Updater.app" "$SPARKLE"; do
  codesign --force --options runtime "${TIMESTAMP[@]}" --sign "$IDENTITY" "$code"
done
codesign --force --options runtime "${TIMESTAMP[@]}" --sign "$IDENTITY" --identifier "$BUNDLE_ID" "$OUT"
codesign --verify --strict --verbose=2 "$OUT"

REQ="$(codesign -d -r- "$OUT" 2>&1 | grep '^designated' || true)"
if [[ "${ALLOW_ADHOC:-0}" != 1 && ( "$REQ" == *cdhash* || "$REQ" != *"identifier \"$BUNDLE_ID\""* ) ]]; then
  print -u2 "refusing: the designated requirement would not survive a rebuild"
  print -u2 -- "$REQ"
  exit 1
fi
print -- "$REQ"
