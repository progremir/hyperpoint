#!/bin/zsh
# Builds, signs and checks Hyperpoint.app at the path given ($1), stamped with an optional version ($2).
# TCC keys the Accessibility and Input Monitoring grants to the app's designated requirement. An ad-hoc signature
# makes that a cdhash, which changes on every build and silently revokes both grants, so this refuses one unless
# ALLOW_ADHOC=1 (CI builds that only check the pipeline).
set -euo pipefail
cd "${0:A:h}/.."

OUT="${1:?usage: build-app.sh <path/Hyperpoint.app> [version]}"
VERSION="${2:-}"
IDENTITY="${SIGN_IDENTITY:-Apple Development: Emir Amanbekov (KGBFPV5MVR)}"
BUNDLE_ID="dev.emir.hyperpoint"

scripts/check-layers.sh
swift build -c release --product Hyperpoint
BIN="$(swift build -c release --show-bin-path)/Hyperpoint"

rm -rf "$OUT"
mkdir -p "$OUT/Contents/MacOS" "$OUT/Contents/Resources"
cp "$BIN" "$OUT/Contents/MacOS/Hyperpoint"
cp Support/Info.plist "$OUT/Contents/Info.plist"
if [[ -n "$VERSION" ]]; then
  plutil -replace CFBundleShortVersionString -string "$VERSION" "$OUT/Contents/Info.plist"
  plutil -replace CFBundleVersion -string "$(git rev-list --count HEAD)" "$OUT/Contents/Info.plist"
fi
# Icons are generated by design/logo/build.py; the bundle takes them straight from the kit.
cp design/logo/macos/AppIcon.icns design/logo/macos/MenuBarTemplate.png design/logo/macos/MenuBarTemplate@2x.png \
  "$OUT/Contents/Resources/"
plutil -lint "$OUT/Contents/Info.plist" >/dev/null

codesign --force --sign "$IDENTITY" --identifier "$BUNDLE_ID" "$OUT"
codesign --verify --strict --verbose=2 "$OUT"

REQ="$(codesign -d -r- "$OUT" 2>&1 | grep '^designated' || true)"
if [[ "${ALLOW_ADHOC:-0}" != 1 && ( "$REQ" == *cdhash* || "$REQ" != *"identifier \"$BUNDLE_ID\""* ) ]]; then
  print -u2 "refusing: the designated requirement would not survive a rebuild"
  print -u2 -- "$REQ"
  exit 1
fi
print -- "$REQ"
